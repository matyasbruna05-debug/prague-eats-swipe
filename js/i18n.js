// Czech / English UI strings. t('key', {vars}) returns the current language; choice() translates quiz options by id.
// Language: ?lang=cs|en, then the saved choice, then the browser language (cs/sk -> Czech, anything else -> English).

const LKEY = 'pragueEatsSwipe.lang';
const fromUrl = new URLSearchParams(location.search).get('lang');
let saved = null;
try {
  saved = localStorage.getItem(LKEY);
} catch {}
export let lang = ['cs', 'en'].includes(fromUrl) ? fromUrl : ['cs', 'en'].includes(saved) ? saved : /^(cs|sk)\b/i.test(navigator.language || '') ? 'cs' : 'en';

export function setLang(l) {
  lang = l === 'en' ? 'en' : 'cs';
  try {
    localStorage.setItem(LKEY, lang);
  } catch {}
  document.documentElement.lang = lang;
}

// Plural: cs has 1 / 2-4 / 5+, en has 1 / other.
export function plural(n, forms) {
  const f = forms[lang];
  if (lang === 'en') return n === 1 ? f[0] : f[1];
  return n === 1 ? f[0] : n >= 2 && n <= 4 ? f[1] : f[2];
}
